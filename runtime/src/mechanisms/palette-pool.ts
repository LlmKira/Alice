const replied = (e: Example, reply: readonly string[]): Example => {
  const last = e.acts.at(-1);
  const sticker = last?.kind === "sticker" ? [last] : [];
  const first = e.acts[0];
  return {
    ...e,
    acts: [...says([...reply], first?.kind === "send" ? first.replyTo : null), ...sticker],
  };
};

