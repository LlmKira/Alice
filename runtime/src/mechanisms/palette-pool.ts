/** 一句一条 say；replyTo 只挂在第一条上。 */
const says = (reply: string[], replyTo: string | null = null): Act[] =>
  reply.map((text, i) => ({ kind: "send", text, replyTo: i === 0 ? replyTo : null }));
const p = (register: Register, scene: string, reply: string[], sticker?: string): Example => ({
  register,
  chat: "private",
  scene,
  acts: [...says(reply), ...(sticker ? [{ kind: "sticker" as const, word: sticker }] : [])],
  source: "context",
});
const g = (
  register: Register,
  scene: string,
  reply: string[],
  extra: { replyTo?: string } = {},
): Example => ({
  register,
  chat: "group",
  scene,
  acts: says(reply, extra.replyTo ?? null),
  source: "context",
});

